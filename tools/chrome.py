def stamp(text):
    """?v= for the shared stylesheet/script and for the planner script, so browsers never mix old and new files."""
    import hashlib
    v = hashlib.sha1((ROOT / "site.css").read_bytes() + (ROOT / "site.js").read_bytes()).hexdigest()[:7]
    pv = hashlib.sha1((ROOT / "routenplaner" / "planner.js").read_bytes()).hexdigest()[:7]
    text = re.sub(r"(site\.(?:css|js))\?v=[0-9a-f]{7}", rf"\1?v={v}", text)
    return re.sub(r"(planner\.js)\?v=[0-9a-f]{7}", rf"\1?v={pv}", text)


MARK = re.compile(r"const EN = \{(/\*chrome\*/.*?/\*end\*/)?", re.S)


def apply(text, prefix, current):
    text = re.sub(r'<header class="top">.*?</header>', lambda m: header(prefix, current), text, count=1, flags=re.S)
    text = re.sub(r'<footer class="foot">.*?</footer>', lambda m: footer(prefix), text, count=1, flags=re.S)
    block = "/*chrome*/" + json.dumps(EN, ensure_ascii=False)[1:-1] + ",/*end*/"
    return MARK.sub(lambda m: "const EN = {" + block, text, count=1)


def main():
    stale = []
    for page in sorted(ROOT.glob("**/index.html")):
        rel = page.relative_to(ROOT)
        if any(p.startswith(".") or p in ("services", "node_modules") for p in rel.parts):
            continue
        text = page.read_text()
        if "Generated by tools/landing.py" in text:
            continue
        if '<header class="top">' not in text:
            new = stamp(text)
            if new != text and "--check" not in sys.argv:
                page.write_text(new)
            continue
        depth = len(rel.parts) - 1
        current = "" if depth == 0 else rel.parent.as_posix() + "/"
        new = stamp(apply(text, "../" * depth, current))
        if new != text:
            if "--check" in sys.argv:
                stale.append(str(rel))
            else:
                page.write_text(new)
    if stale:
        raise SystemExit("Header/footer out of date, run python3 tools/chrome.py: " + ", ".join(stale))


if __name__ == "__main__":
    main()
